using System;

class Program
{
    static void Main()
    {
        //o 'for tem 3 partes:
        //1. comeca com i = 1;
        //2. repete enquanto o i <= 10;
        //3. aumenta 1 em 'i' a cada repetição (i++)
        for (int i = 1; i <=10; i++)
        {
            Console.WriteLine("esta é a repetição numero: " + i);
        }
    }
}